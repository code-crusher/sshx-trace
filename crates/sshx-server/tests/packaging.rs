//! Tests for the packaging metadata used by `cargo-deb` and
//! `cargo-generate-rpm` (see `scripts/package.sh` and issue #35).
//!
//! These tests verify that the files referenced by the `[package.metadata]`
//! tables in `Cargo.toml` actually exist, so that building deb/rpm packages
//! does not fail with a missing asset error.

use std::path::{Path, PathBuf};

/// Returns the path to the crate root, based on the location of this test
/// file.
fn crate_root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).to_path_buf()
}

/// The gzipped manual page referenced by the packaging metadata, which is
/// generated by `scripts/package.sh` from a checked-in roff source file.
const MAN_PAGE: &str = "packaging/man/sshx-server.1.gz";

#[test]
fn test_packaging_files_exist() {
    let root = crate_root();
    let cargo_toml = std::fs::read_to_string(root.join("Cargo.toml")).unwrap();

    // Every file referenced by the deb and rpm metadata must be listed here.
    for file in [MAN_PAGE, "packaging/description.txt"] {
        assert!(
            cargo_toml.contains(&format!("\"{file}\"")),
            "expected `Cargo.toml` to reference `{file}` in its packaging metadata"
        );
    }

    assert!(
        root.join("packaging/description.txt").is_file(),
        "expected the extended description file to exist"
    );
    // The compressed manual page is generated from its roff source file, so
    // the source must be checked in for packaging to work.
    assert!(
        root.join(MAN_PAGE.trim_end_matches(".gz")).is_file(),
        "expected the manual page source `{}` to exist",
        MAN_PAGE.trim_end_matches(".gz")
    );
}
